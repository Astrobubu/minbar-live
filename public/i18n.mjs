const saved = localStorage.getItem('minbar-ui-lang');
export let uiLang = saved === 'ar' || saved === 'en' ? saved : (navigator.language || '').startsWith('ar') ? 'ar' : 'en';

export function t(text, vars = {}) {
  const template = (uiLang === 'ar' && ar[text]) || text;
  return template.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? '');
}

export function applyUiLang() {
  const root = document.documentElement;
  root.lang = uiLang;
  root.dir = uiLang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    node.dataset.i18n ||= node.textContent.trim();
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-label]').forEach((node) => {
    node.dataset.i18nLabel ||= node.getAttribute('aria-label');
    node.setAttribute('aria-label', t(node.dataset.i18nLabel));
  });
  document.querySelectorAll('.lang-toggle').forEach((node) => {
    node.textContent = uiLang === 'ar' ? 'English' : 'العربية';
    node.lang = uiLang === 'ar' ? 'en' : 'ar';
  });
}

export function toggleUiLang() {
  uiLang = uiLang === 'ar' ? 'en' : 'ar';
  localStorage.setItem('minbar-ui-lang', uiLang);
  applyUiLang();
}
